export function getSwapCandidates(exerciseId) {
  const source = exercises.find(e => e.id === exerciseId);
  if (!source) return [];
  return exercises.filter(e =>
    e.id !== exerciseId &&
    e.jointActions.some(action => source.jointActions.includes(action))
  );
}

export function getByJointAction(jointAction) {
  return exercises.filter(e => e.jointActions.includes(jointAction));
}

export function getByMuscle(muscleGroup) {
  return exercises.filter(e => e.muscles.includes(muscleGroup));
}
